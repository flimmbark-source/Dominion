function resolveWeaponType(weaponType){
  if (!weaponType) return 'dagger';
  const key = weaponType.toString().toLowerCase();
  return WEAPON_SWING_CONFIGS[key]
    ? key
    : (WEAPON_SWING_ALIASES[key] || 'dagger');
}

function getWeaponSwingConfig(weaponType){
  const resolved = resolveWeaponType(weaponType);
  return WEAPON_SWING_CONFIGS[resolved] || WEAPON_SWING_CONFIGS.dagger;
}

export { getWeaponSwingConfig, resolveWeaponType };
